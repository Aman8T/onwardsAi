"""Profile persistence.

Each analysis is kept as one record, ``{"profile": Profile, "context": StoredContext}``: the profile
the graph renders plus everything the chat needs. A context is ``{"sources": [{id, label, kind, url?,
content}], "readers": {sourceId: reader output}}``, the same shape as the Node server's StoredContext
and of sample-context.json. Records live in memory, so reads are instant, and are mirrored best-effort
to JSON files under DATA_DIR/profiles/<id>.json so a restarted worker can still serve and chat about an
earlier analysis (the cloud filesystem is ephemeral, so this is a cache, not a database). The bundled
sample profile (SAMPLE_DIR) is served as a fallback for its own id, so the offline demo can chat too.
"""

from __future__ import annotations

import asyncio
import json
import os
import re
import uuid
from pathlib import Path
from typing import Any, TypeGuard

from .config import DATA_DIR, SAMPLE_DIR
from ..sample import load_sample_sources

PROFILE_DIR = DATA_DIR / "profiles"
SAMPLE_PROFILE_PATH = SAMPLE_DIR / "sample-profile.json"
SAMPLE_CONTEXT_PATH = SAMPLE_DIR / "sample-context.json"

MAX_RECORDS = 200
"""Records kept in memory; the oldest are dropped first (they stay on disk when the write succeeded)."""

_ID = re.compile(r"^[a-z0-9][a-z0-9_-]{0,80}$", re.IGNORECASE)
"""Ids are generated by the pipeline; anything else (path tricks, empty) is rejected."""

_records: dict[str, dict[str, Any]] = {}


def _empty_context() -> dict[str, Any]:
    return {"sources": [], "readers": {}}


def _valid_id(pid: object) -> TypeGuard[str]:
    return isinstance(pid, str) and bool(_ID.match(pid))


def _file_for(pid: str) -> Path:
    return PROFILE_DIR / f"{pid}.json"


def _remember(pid: str, record: dict[str, Any]) -> None:
    _records.pop(pid, None)
    _records[pid] = record
    while len(_records) > MAX_RECORDS:
        del _records[next(iter(_records))]


# ───────────────────────── disk (always called through asyncio.to_thread) ─────────────────────────


def _read_json(path: Path) -> Any:
    """Parsed JSON, or None when the file is missing or unreadable."""
    try:
        with path.open(encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def _json_default(value: object) -> None:
    """Blobs (a scanned resume's bytes) are not worth persisting; anything else unexpected is an error."""
    if isinstance(value, bytes | bytearray):
        return None
    raise TypeError(f"not JSON serialisable: {type(value).__name__}")


def _write_json(path: Path, data: Any) -> None:
    """Atomic write: a sibling temp file renamed into place, so readers never see a partial file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.{uuid.uuid4().hex}.tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, default=_json_default), encoding="utf-8")
    os.replace(tmp, path)


def _is_record(value: object) -> bool:
    return isinstance(value, dict) and isinstance(value.get("profile"), dict) and bool(value["profile"].get("id"))


def _is_context(value: object) -> bool:
    return isinstance(value, dict) and isinstance(value.get("sources"), list) and isinstance(value.get("readers"), dict)


def _sample_record(pid: str) -> dict[str, Any] | None:
    """The bundled sample profile, when its id is asked for (e.g. after "Try a sample profile" offline)."""
    profile = get_sample_profile()
    if not profile or profile.get("id") != pid:
        return None
    context = _read_json(SAMPLE_CONTEXT_PATH)
    if not _is_context(context):
        # No pre-computed context: the chat still gets the raw fixture text, just no reader findings.
        context = {
            "sources": [
                {"id": s.id, "label": s.label, "kind": s.kind, **({"url": s.url} if s.url else {}), "content": s.text}
                for s in load_sample_sources()
            ],
            "readers": {},
        }
    return {"profile": profile, "context": context}


def _load_from_disk(pid: str) -> dict[str, Any] | None:
    record = _read_json(_file_for(pid))
    if not _is_record(record):
        return _sample_record(pid)
    if not _is_context(record.get("context")):
        record["context"] = _empty_context()
    return record


# ───────────────────────── public API ─────────────────────────


def has_sample_profile() -> bool:
    return SAMPLE_PROFILE_PATH.is_file()


def get_sample_profile() -> dict[str, Any] | None:
    """The pre-computed sample profile, or None when the fixture is missing or malformed."""
    profile = _read_json(SAMPLE_PROFILE_PATH)
    return profile if isinstance(profile, dict) and profile.get("id") else None


async def _persist(pid: str) -> None:
    try:
        await asyncio.to_thread(_write_json, _file_for(pid), _records[pid])
    except (OSError, TypeError, ValueError) as exc:
        print(f"[store] could not write {pid}.json: {exc}", flush=True)


async def _load(pid: str) -> dict[str, Any] | None:
    if not _valid_id(pid):
        return None
    record = _records.get(pid)
    if record is None:
        record = await asyncio.to_thread(_load_from_disk, pid)
        if record is not None:
            _remember(pid, record)
    return record


async def save_profile(profile: dict[str, Any]) -> None:
    """Store a Profile (keyed by profile["id"]); an earlier context for the same id is kept."""
    pid = profile.get("id")
    if not _valid_id(pid):
        raise ValueError(f"invalid profile id: {pid!r}")
    previous = _records.get(pid)
    _remember(pid, {"profile": profile, "context": previous["context"] if previous else _empty_context()})
    await _persist(pid)


async def save_context(pid: str, ctx: dict[str, Any]) -> None:
    """Store a profile's chat context: {"sources": [{id, label, kind, url?, content}], "readers": {id: output}}."""
    if not _valid_id(pid):
        raise ValueError(f"invalid profile id: {pid!r}")
    if not _is_context(ctx):
        raise ValueError("context must have a 'sources' list and a 'readers' dict")
    previous = _records.get(pid)
    _remember(pid, {"profile": previous["profile"] if previous else None, "context": ctx})
    await _persist(pid)


async def get_profile(pid: str) -> dict[str, Any] | None:
    record = await _load(pid)
    return record["profile"] if record else None


async def get_context(pid: str) -> dict[str, Any] | None:
    record = await _load(pid)
    return record["context"] if record else None
