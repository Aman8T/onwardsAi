"""Questions: at most three things to ask the person, for the gaps and unknowns that matter most.

Generated by code from the coverage rows and the gate answers (no model): an uncertain hard condition first, then
must-haves, then required rows; within a tier an unknown comes before a gap, and a gap before a partial match. A row
that is covered, or that the person already has but the resume lacks, asks nothing. An answer becomes a fact in the
person's own words and the rows are re-checked; seeing a gap, answering and re-checking are free.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Final

from tayyari.contract.match import MAX_QUESTIONS, Coverage, GateAnswer, Posting, Question
from tayyari.match.text import clip

_TIER_RANK: Final = {"must": 0, "required": 1, "preferred": 2}
_STATUS_RANK: Final = {"unknown": 0, "missing_gap": 1, "partial": 2, "synonym_only": 3}


def make_questions(
    posting: Posting,
    coverage: Sequence[Coverage],
    answers: Sequence[GateAnswer],
    *,
    limit: int = MAX_QUESTIONS,
) -> list[Question]:
    """The questions for this match, most important first, at most ``limit`` (never more than three)."""
    ranked: list[tuple[tuple[int, int, int], Question]] = []

    gates = {g.id: g for g in posting.gates}
    for answer in answers:
        gate = gates.get(answer.gateId)
        if gate is None or answer.verdict != "uncertain":
            continue
        ranked.append(
            (
                (0, -gate.severity, 0),
                Question(
                    id=f"q-{gate.id}",
                    gateId=gate.id,
                    text=f"{clip(gate.question, 200)} Answer in your own words; we keep it as something you said.",
                    why="A hard condition in the posting. Nothing in your documents settles it, and it decides whether the role is open to you.",
                ),
            )
        )

    reqs = {r.id: r for r in posting.requirements}
    for row in coverage:
        req = reqs.get(row.requirementId)
        if req is None or req.tier not in _TIER_RANK or row.status not in _STATUS_RANK:
            continue
        what = clip(req.text, 160)
        if row.status == "unknown":
            text = f"Have you done this: {what}? If so, tell us what you did, in your own words."
            why = f"The posting asks for it ({req.tier}) and your evidence doesn't say either way."
        elif row.status == "missing_gap":
            text = f"The posting asks for {what}. Is there any work of yours, in a job or outside one, that shows it?"
            why = f"We can't find it in your resume or links ({req.tier}). If you have it, it becomes evidence; if not, it stays an honest gap."
        else:
            text = (
                f"The posting asks for {what}. Your evidence shows part of it: what else have you done here?"
            )
            why = f"Your evidence covers this only partly ({req.tier}); a specific example would firm it up."
        ranked.append(
            (
                (1, _TIER_RANK[req.tier], _STATUS_RANK[row.status]),
                Question(id=f"q-{req.id}", requirementId=req.id, text=text, why=why),
            )
        )

    ranked.sort(key=lambda item: item[0])
    return [q for _, q in ranked[: max(0, min(limit, MAX_QUESTIONS))]]


__all__ = ["make_questions"]
