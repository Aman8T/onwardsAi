/**
 * Profile persistence: one JSON file per analysis under data/profiles/<id>.json, holding the Profile
 * plus the context the chat needs (raw source text and every reader's output). An in-memory cache
 * keeps reads instant. The pre-computed sample profile (server/sample) is served as a fallback, so
 * the offline demo can chat too.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Profile, SourceKind } from '../shared/types.ts';
import type { ReaderOutput } from './schemas.ts';
import { SAMPLE_CONTEXT_PATH, loadSampleProfile, loadSampleSources } from './sample/index.ts';

export interface StoredContext {
  sources: Array<{ id: string; label: string; kind: SourceKind; url?: string; content: string }>;
  readers: Record<string, ReaderOutput>;
}

interface StoredRecord {
  profile: Profile;
  context: StoredContext;
}

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DATA_DIR = join(ROOT, 'data');
const PROFILE_DIR = join(DATA_DIR, 'profiles');

function ensureDirs() {
  mkdirSync(PROFILE_DIR, { recursive: true });
  const ignore = join(DATA_DIR, '.gitignore');
  if (!existsSync(ignore)) writeFileSync(ignore, '*\n');
}

const cache = new Map<string, StoredRecord>();

/** Ids are generated by us; anything else (path tricks, empty) is rejected. */
const validId = (id: string) => /^[a-z0-9][a-z0-9_-]{0,80}$/i.test(id);
const fileFor = (id: string) => join(PROFILE_DIR, `${id}.json`);

export async function saveProfile(profile: Profile, context: StoredContext): Promise<void> {
  if (!validId(profile.id)) throw new Error(`invalid profile id: ${profile.id}`);
  ensureDirs();
  const record: StoredRecord = { profile, context };
  cache.set(profile.id, record);
  const target = fileFor(profile.id);
  const tmp = `${target}.${process.pid}.tmp`;
  await writeFile(tmp, JSON.stringify(record), 'utf8');
  await rename(tmp, target);
}

async function load(id: string): Promise<StoredRecord | null> {
  if (!validId(id)) return null;
  const hit = cache.get(id);
  if (hit) return hit;
  try {
    const record = JSON.parse(await readFile(fileFor(id), 'utf8')) as StoredRecord;
    if (!record?.profile?.id) return null;
    record.context ??= { sources: [], readers: {} };
    cache.set(id, record);
    return record;
  } catch {
    return loadSampleRecord(id);
  }
}

/** The bundled sample profile, when its id is asked for (e.g. after "Try a sample profile" offline). */
async function loadSampleRecord(id: string): Promise<StoredRecord | null> {
  const profile = loadSampleProfile();
  if (!profile || profile.id !== id) return null;
  let context: StoredContext | null = null;
  try {
    context = JSON.parse(await readFile(SAMPLE_CONTEXT_PATH, 'utf8')) as StoredContext;
  } catch {
    context = {
      sources: loadSampleSources().map((s) => ({ id: s.id, label: s.label, kind: s.kind, url: s.url, content: s.content })),
      readers: {},
    };
  }
  const record = { profile, context };
  cache.set(id, record);
  return record;
}

export async function getProfile(id: string): Promise<Profile | null> {
  return (await load(id))?.profile ?? null;
}

export async function getContext(id: string): Promise<StoredContext | null> {
  return (await load(id))?.context ?? null;
}
